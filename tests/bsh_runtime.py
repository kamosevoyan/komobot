class JSONException(Exception):
    """Raised on missing required keys in MockJSONObject / MockJSONArray."""


class MockJSONObject:
    """Minimal Android org.json.JSONObject compatible wrapper."""

    def __init__(self, raw: str | dict[str, Any] | None = None) -> None:
        if raw is None:
            self._data: dict[str, Any] = {}
        elif isinstance(raw, str):
            parsed = json.loads(raw)
            if not isinstance(parsed, dict):
                raise JSONException("Expected JSON object")
            self._data = {k: _wrap_json_value(v) for k, v in parsed.items()}
        elif isinstance(raw, dict):
            self._data = {k: _wrap_json_value(v) for k, v in raw.items()}
        else:
            raise TypeError(f"Unsupported JSONObject init: {type(raw)}")

    def put(self, key: str, value: Any) -> MockJSONObject:
        self._data[key] = value
        return self

    def has(self, key: str) -> bool:
        return key in self._data

    def remove(self, key: str) -> Any:
        return self._data.pop(key, None)

    def optLong(self, key: str, default: int = 0) -> int:
        val = self._data.get(key)
        if isinstance(val, bool) or not isinstance(val, (int, float)):
            return int(default)
        return int(val)

    def optInt(self, key: str, default: int = 0) -> int:
        return self.optLong(key, default)

    def optBoolean(self, key: str, default: bool = False) -> bool:
        val = self._data.get(key)
        if isinstance(val, bool):
            return val
        return bool(default)

    def optString(self, key: str, default: str = "") -> str:
        val = self._data.get(key)
        if val is None:
            return default
        if isinstance(val, str):
            return val
        return _java_str(val)

    def optJSONArray(self, key: str) -> MockJSONArray | None:
        val = self._data.get(key)
        return val if isinstance(val, MockJSONArray) else None

    def optJSONObject(self, key: str) -> MockJSONObject | None:
        val = self._data.get(key)
        return val if isinstance(val, MockJSONObject) else None

    def getJSONObject(self, key: str) -> MockJSONObject:
        val = self._data.get(key)
        if not isinstance(val, MockJSONObject):
            raise JSONException(f"No value for {key}")
        return val

    def getJSONArray(self, key: str) -> MockJSONArray:
        val = self._data.get(key)
        if not isinstance(val, MockJSONArray):
            raise JSONException(f"No value for {key}")
        return val

    def to_python(self) -> dict[str, Any]:
        return {k: _unwrap_json_value(v) for k, v in self._data.items()}

    def toString(self, indent: int | None = None) -> str:
        return json.dumps(self.to_python(), indent=indent, ensure_ascii=False)

    def names(self) -> MockJSONArray | None:
        if not self._data:
            return None
        return MockJSONArray(list(self._data.keys()))


class MockJSONArray:
    """Minimal Android org.json.JSONArray compatible wrapper."""

    def __init__(self, items: list[Any] | None = None) -> None:
        self._items: list[Any] = (
            [_wrap_json_value(x) for x in items] if items is not None else []
        )

    def length(self) -> int:
        return len(self._items)

    def put(self, value: Any) -> MockJSONArray:
        self._items.append(value)
        return self

    def get(self, index: int) -> Any:
        if index < 0 or index >= len(self._items):
            raise JSONException(f"Index {index} out of bounds")
        return self._items[index]

    def optString(self, index: int, default: str = "") -> str:
        if 0 <= index < len(self._items):
            val = self._items[index]
            if val is None:
                return default
            return val if isinstance(val, str) else _java_str(val)
        return default

    def getJSONObject(self, index: int) -> MockJSONObject:
        val = self.get(index)
        if not isinstance(val, MockJSONObject):
            raise JSONException(f"Index {index} is not a JSONObject")
        return val

    def optJSONObject(self, index: int) -> MockJSONObject | None:
        if 0 <= index < len(self._items):
            val = self._items[index]
            if isinstance(val, MockJSONObject):
                return val
        return None

    def optLong(self, index: int, default: int = 0) -> int:
        if 0 <= index < len(self._items):
            val = self._items[index]
            if not isinstance(val, bool) and isinstance(val, (int, float)):
                return int(val)
        return int(default)

    def to_python(self) -> list[Any]:
        return [_unwrap_json_value(x) for x in self._items]


def _wrap_json_value(val: Any) -> Any:
    if isinstance(val, dict):
        return MockJSONObject(val)
    if isinstance(val, list):
        return MockJSONArray(val)
    return val


def _unwrap_json_value(val: Any) -> Any:
    if isinstance(val, (MockJSONObject, MockJSONArray)):
        return val.to_python()
    return val


class _CompressFormat:
    PNG = "PNG"
    JPEG = "JPEG"


class MockBitmap:
    """Contiguous RGB pixel buffer modeling android.graphics.Bitmap."""

    CompressFormat = _CompressFormat

    def __init__(self, width: int, height: int, fill: tuple[int, int, int] = (0, 0, 0)):
        self.width = width
        self.height = height
        rgb = bytes((fill[0] & 0xFF, fill[1] & 0xFF, fill[2] & 0xFF))
        self._rgb = bytearray(rgb * (width * height))
        self.recycled = False

    def getWidth(self) -> int:
        return self.width

    def getHeight(self) -> int:
        return self.height

    def getPixel(self, x: int, y: int) -> int:
        idx = (y * self.width + x) * 3
        return (
            0xFF000000
            | (self._rgb[idx] << 16)
            | (self._rgb[idx + 1] << 8)
            | self._rgb[idx + 2]
        )

    def set_pixel(self, x: int, y: int, r: int, g: int, b: int) -> None:
        if 0 <= x < self.width and 0 <= y < self.height:
            idx = (y * self.width + x) * 3
            self._rgb[idx] = r & 0xFF
            self._rgb[idx + 1] = g & 0xFF
            self._rgb[idx + 2] = b & 0xFF

    def fill_rect(
        self, x1: int, y1: int, x2: int, y2: int, r: int, g: int, b: int
    ) -> None:
        """Fill inclusive rectangle [x1..x2, y1..y2] with RGB color."""
        x_lo = max(0, x1)
        x_hi = min(self.width - 1, x2)
        y_lo = max(0, y1)
        y_hi = min(self.height - 1, y2)
        if x_lo > x_hi or y_lo > y_hi:
            return
        row_bytes = bytes((r & 0xFF, g & 0xFF, b & 0xFF)) * (x_hi - x_lo + 1)
        row_len = len(row_bytes)
        stride = self.width * 3
        col_off = x_lo * 3
        for y in range(y_lo, y_hi + 1):
            start = y * stride + col_off
            self._rgb[start : start + row_len] = row_bytes

    def recycle(self) -> None:
        self.recycled = True

    def compress(
        self, fmt: str, quality: int, baos: _MockByteArrayOutputStream
    ) -> bool:
        del fmt, quality
        stride = self.width * 3
        mv = memoryview(self._rgb)
        raw_rows = b"".join(
            b"\x00" + mv[y * stride : (y + 1) * stride].tobytes()
            for y in range(self.height)
        )

        def chunk(tag: bytes, payload: bytes) -> bytes:
            body = tag + payload
            return (
                struct.pack("!I", len(payload))
                + body
                + struct.pack("!I", zlib.crc32(body) & 0xFFFFFFFF)
            )

        ihdr = struct.pack("!IIBBBBB", self.width, self.height, 8, 2, 0, 0, 0)
        idat = zlib.compress(raw_rows, level=1)
        png = (
            b"\x89PNG\r\n\x1a\n"
            + chunk(b"IHDR", ihdr)
            + chunk(b"IDAT", idat)
            + chunk(b"IEND", b"")
        )
        baos.write(png)
        return True

    @staticmethod
    def createBitmap(src: MockBitmap, cx: int, cy: int, cw: int, ch: int) -> MockBitmap:
        out = MockBitmap(cw, ch)
        src_stride = src.width * 3
        dst_stride = cw * 3
        col_off = cx * 3
        for y in range(ch):
            src_start = (cy + y) * src_stride + col_off
            dst_start = y * dst_stride
            out._rgb[dst_start : dst_start + dst_stride] = src._rgb[
                src_start : src_start + dst_stride
            ]
        return out


@dataclass
class VirtualFileEntry:
    data: bytes
    mtime_ms: int
    bitmap: MockBitmap | None = None


class MockAndroidEnv:
    """Simulated Android device filesystem, clock, Bitmaps, and Telegram API."""

    def __init__(self, now_ms: int = 1794735000000) -> None:
        self.now_ms = now_ms
        self.files: dict[str, VirtualFileEntry] = {}
        self.tg_calls: list[dict[str, Any]] = []
        self.http_connections: list[dict[str, Any]] = []
        self.next_message_id = 1000
        self.http_status_overrides: dict[str, int] = {}
        self.http_error_bodies: dict[str, dict[str, Any]] = {}
        self.guest_adb_mode: str = "down"
        self.guest_adb_commands: list[str] = []
        self.guest_adb_responses: dict[str, str] = {}
        self.guest_adb_pubkey_sent: bool = False
        self.lock = threading.RLock()

    def advance_time(self, ms: int) -> None:
        if ms > 0:
            self.now_ms += ms

    def write_text(self, path: str, text: str, mtime_ms: int | None = None) -> None:
        self.files[path] = VirtualFileEntry(
            data=text.encode("utf-8"),
            mtime_ms=self.now_ms if mtime_ms is None else mtime_ms,
        )

    def read_text(self, path: str) -> str:
        return self.files[path].data.decode("utf-8")

    def read_config(
        self, path: str = "/storage/emulated/0/Download/komobot_config.json"
    ) -> dict[str, Any]:
        return json.loads(self.read_text(path))

    def write_config(
        self,
        cfg: dict[str, Any],
        path: str = "/storage/emulated/0/Download/komobot_config.json",
    ) -> None:
        self.write_text(path, json.dumps(cfg, indent=2, ensure_ascii=False))

    def add_screenshot(
        self,
        name: str,
        bmp: MockBitmap | None,
        size: int = 120_000,
        mtime_ms: int | None = None,
        directory: str = "/storage/emulated/0/DCIM/Screenshots",
        with_thumbnail: bool = False,
        truncated: bool = False,
    ) -> str:
        path = posixpath.join(directory, name)
        mtime = self.now_ms if mtime_ms is None else mtime_ms
        lower = name.lower()
        if lower.endswith(".png"):
            header = b"\x89PNG\r\n\x1a\n"
            trailer = b"" if truncated else b"\x00\x00\x00\x00IEND\xaeB`\x82"
        else:
            header = b"\xff\xd8"
            trailer = b"" if truncated else b"\xff\xd9"
        body_len = max(0, size - len(header) - len(trailer))
        self.files[path] = VirtualFileEntry(
            data=header + b"0" * body_len + trailer, mtime_ms=mtime, bitmap=bmp
        )
        if with_thumbnail:
            thumb_path = posixpath.join(directory, f"thumbnail_{name}")
            self.files[thumb_path] = VirtualFileEntry(data=b"thumb", mtime_ms=mtime)
        return path

    def handle_http(
        self, url_str: str, body: bytes, content_type: str
    ) -> tuple[int, str]:
        method = url_str.rsplit("/", 1)[-1]
        status = self.http_status_overrides.get(method, 200)
        if method in ("sendPhoto", "editMessageMedia", "sendDocument"):
            record = _parse_multipart_form(body, content_type)
            self.tg_calls.append({"method": method, "status": status, **record})
            if status >= 400:
                err_body = self.http_error_bodies.get(
                    method,
                    {
                        "ok": False,
                        "error_code": status,
                        "description": f"HTTP {status} error",
                    },
                )
                return status, json.dumps(err_body)
            if method == "editMessageMedia":
                mid = int(record.get("message_id", 9999))
            elif method == "sendDocument":
                self.next_message_id += 1
                mid = self.next_message_id
            else:
                mid = 9999
            return status, json.dumps({"ok": True, "result": {"message_id": mid}})

        payload = json.loads(body.decode("utf-8")) if body else {}
        self.tg_calls.append({"method": method, "status": status, "payload": payload})
        if status >= 400:
            err_body = self.http_error_bodies.get(
                method,
                {
                    "ok": False,
                    "error_code": status,
                    "description": f"HTTP {status} error",
                },
            )
            return status, json.dumps(err_body)
        self.next_message_id += 1
        return status, json.dumps(
            {"ok": True, "result": {"message_id": self.next_message_id}}
        )


def _parse_multipart_form(body: bytes, content_type: str) -> dict[str, Any]:
    match = re.search(r"boundary=([^\s;]+)", content_type)
    boundary = match.group(1).encode("ascii") if match else b""
    parts = body.split(b"--" + boundary)
    parsed: dict[str, Any] = {}
    for part in parts:
        if not part or part in (b"--\r\n", b"--"):
            continue
        header_end = part.find(b"\r\n\r\n")
        if header_end < 0:
            continue
        headers = part[:header_end].decode("utf-8", errors="replace")
        content = part[header_end + 4 :]
        if content.endswith(b"\r\n"):
            content = content[:-2]
        name_m = re.search(r'name="([^"]+)"', headers)
        if not name_m:
            continue
        field_name = name_m.group(1)
        if field_name in ("photo", "document"):
            fname_m = re.search(r'filename="([^"]+)"', headers)
            parsed["filename"] = fname_m.group(1) if fname_m else ""
            parsed[f"{field_name}_bytes"] = content
        else:
            parsed[field_name] = content.decode("utf-8", errors="replace")
    return parsed


class _MockFile:
    def __init__(self, env: MockAndroidEnv, path: str) -> None:
        self._env = env
        self.path = posixpath.normpath(path)

    def exists(self) -> bool:
        if self.path in self._env.files:
            return True
        prefix = self.path.rstrip("/") + "/"
        return any(p.startswith(prefix) for p in self._env.files)

    def isDirectory(self) -> bool:
        if self.path in self._env.files:
            return False
        return self.path.endswith(("/Screenshots", "/komobot_ss")) or any(
            p.startswith(self.path + "/") for p in self._env.files
        )

    def isFile(self) -> bool:
        return self.path in self._env.files

    def getParentFile(self) -> _MockFile | None:
        parent = posixpath.dirname(self.path)
        return _MockFile(self._env, parent) if parent else None

    def mkdirs(self) -> bool:
        return True

    def listFiles(self) -> list[_MockFile] | None:
        prefix = self.path.rstrip("/") + "/"
        items = [
            _MockFile(self._env, p)
            for p in sorted(self._env.files)
            if p.startswith(prefix) and "/" not in p[len(prefix) :]
        ]
        return items

    def getName(self) -> str:
        return posixpath.basename(self.path)

    def getAbsolutePath(self) -> str:
        return self.path

    def length(self) -> int:
        entry = self._env.files.get(self.path)
        return len(entry.data) if entry else 0

    def lastModified(self) -> int:
        entry = self._env.files.get(self.path)
        return entry.mtime_ms if entry else 0

    def delete(self) -> bool:
        return self._env.files.pop(self.path, None) is not None

    def renameTo(self, dest: _MockFile) -> bool:
        entry = self._env.files.pop(self.path, None)
        if entry is None:
            return False
        self._env.files[dest.path] = entry
        return True


class _MockByteArrayInputStream:
    def __init__(self, data: bytes, record: dict[str, Any] | None = None) -> None:
        self._data = data
        self._read = False
        self._pos = 0
        self._record = record

    def read(
        self, buf: bytearray | None = None, off: int = 0, length: int | None = None
    ) -> int:
        if buf is None:
            if self._pos >= len(self._data):
                return -1
            b = self._data[self._pos]
            self._pos += 1
            return b
        n = len(buf) - off if length is None else int(length)
        if self._pos >= len(self._data):
            return -1
        avail = min(n, len(self._data) - self._pos)
        buf[off : off + avail] = self._data[self._pos : self._pos + avail]
        self._pos += avail
        return avail

    def read_all_lines(self) -> list[str]:
        if self._read:
            return []
        self._read = True
        if self._record is not None:
            self._record["stream_read"] = True
        return self._data.decode("utf-8", errors="replace").splitlines()

    def close(self) -> None:
        if self._record is not None:
            self._record["stream_closed"] = True


