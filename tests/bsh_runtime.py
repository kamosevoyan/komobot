class _MockHttpURLConnection:
    def __init__(self, env: MockAndroidEnv, url_str: str) -> None:
        self._env = env
        self._url = url_str
        self._headers: dict[str, str] = {}
        self._out = _MockByteArrayOutputStream()
        self._status: int | None = None
        self._resp = ""
        self._conn_record: dict[str, Any] = {
            "method": url_str.rsplit("/", 1)[-1],
            "stream_read": False,
            "stream_closed": False,
            "disconnected": False,
        }
        self._env.http_connections.append(self._conn_record)

    def setRequestMethod(self, method: str) -> None:
        del method

    def setConnectTimeout(self, ms: int) -> None:
        del ms

    def setReadTimeout(self, ms: int) -> None:
        del ms

    def setDoOutput(self, do_output: bool) -> None:
        del do_output

    def setRequestProperty(self, key: str, value: str) -> None:
        self._headers[key] = value

    def getOutputStream(self) -> _MockByteArrayOutputStream:
        return self._out

    def _dispatch(self) -> None:
        if self._status is None:
            ctype = self._headers.get("Content-Type", "")
            self._status, self._resp = self._env.handle_http(
                self._url, self._out.toByteArray(), ctype
            )

    def getResponseCode(self) -> int:
        self._dispatch()
        assert self._status is not None
        return self._status

    def getInputStream(self) -> _MockByteArrayInputStream:
        self._dispatch()
        return _MockByteArrayInputStream(self._resp.encode("utf-8"), self._conn_record)

    def getErrorStream(self) -> _MockByteArrayInputStream:
        self._dispatch()
        return _MockByteArrayInputStream(self._resp.encode("utf-8"), self._conn_record)

    def disconnect(self) -> None:
        self._conn_record["disconnected"] = True


