@dataclass
class _Tok:
    kind: str
    val: Any
    pos: int


def _tokenize(src: str) -> list[_Tok]:
    tokens: list[_Tok] = []
    i = 0
    n = len(src)
    two_char = {"&&", "||", "==", "!=", "<=", ">=", "++", "--", "+=", "-=", ">>", "<<"}
    single_char = set("{}()[];,.?:+-*/%&|^!<>=")
    while i < n:
        ch = src[i]
        if ch.isspace():
            i += 1
            continue
        if src.startswith("//", i):
            nl = src.find("\n", i)
            i = n if nl < 0 else nl + 1
            continue
        if ch == '"':
            start = i
            i += 1
            chars: list[str] = []
            while i < n and src[i] != '"':
                if src[i] == "\\":
                    i += 1
                    esc = src[i]
                    esc_map = {"n": "\n", "r": "\r", "t": "\t", '"': '"', "\\": "\\"}
                    chars.append(esc_map.get(esc, esc))
                else:
                    chars.append(src[i])
                i += 1
            if i >= n:
                raise SyntaxError(f"Unterminated string literal at {start}")
            i += 1
            tokens.append(_Tok("STR", "".join(chars), start))
            continue
        if ch.isdigit():
            start = i
            if src[i : i + 2].lower() == "0x":
                i += 2
                while i < n and src[i] in "0123456789abcdefABCDEF":
                    i += 1
                num = int(src[start:i], 16)
            else:
                while i < n and src[i].isdigit():
                    i += 1
                num = int(src[start:i], 10)
            if i < n and src[i] in "lL":
                i += 1
            tokens.append(_Tok("NUM", num, start))
            continue
        if ch.isalpha() or ch == "_":
            start = i
            while i < n and (src[i].isalnum() or src[i] == "_"):
                i += 1
            word = src[start:i]
            tokens.append(_Tok("IDENT", word, start))
            continue
        if i + 1 < n and src[i : i + 2] in two_char:
            tokens.append(_Tok("OP", src[i : i + 2], i))
            i += 2
            continue
        if ch in single_char:
            tokens.append(_Tok("OP", ch, i))
            i += 1
            continue
        raise SyntaxError(f"Unexpected char {ch!r} at pos {i}")
    tokens.append(_Tok("EOF", "", n))
    return tokens


def _py_ident(name: str) -> str:
    return f"_jvar_{name}" if keyword.iskeyword(name) else name


@dataclass
class _Emitter:
    lines: list[str] = field(default_factory=list)
    indent: int = 0
    loop_id: int = 0

    def emit(self, line: str) -> None:
        self.lines.append(f"{'    ' * self.indent}{line}")

    def source(self) -> str:
        return "\n".join(self.lines)


class _BshToPyCompiler:
    """Compile the BeanShell Java 7 subset used by Komobot into Python source."""

    def __init__(self, tokens: list[_Tok]) -> None:
        self.toks = tokens
        self.idx = 0
        self.em = _Emitter()

    def cur(self, offset: int = 0) -> _Tok:
        pos = min(self.idx + offset, len(self.toks) - 1)
        return self.toks[pos]

    def match(self, kind: str, val: Any = None) -> bool:
        t = self.cur()
        if t.kind != kind:
            return False
        return val is None or t.val == val

    def eat(self, kind: str | None = None, val: Any = None) -> _Tok:
        t = self.cur()
        if kind is not None and t.kind != kind:
            raise SyntaxError(f"Expected {kind} ({val}), got {t}")
        if val is not None and t.val != val:
            raise SyntaxError(f"Expected {val!r}, got {t}")
        self.idx += 1
        return t

    def compile_script(self) -> str:
        self.em.emit("def __bsh_main__():")
        self.em.indent += 1
        while not self.match("EOF"):
            self.parse_stmt()
        if len(self.em.lines) == 1:
            self.em.emit("pass")
        self.em.indent -= 1
        self.em.emit("__bsh_result__ = __bsh_main__()")
        return self.em.source()

    def _looks_like_func_decl(self) -> bool:
        pos = self.idx
        if self.toks[pos].kind != "IDENT" or self.toks[pos].val in _KEYWORDS:
            return False
        pos += 1
        while pos + 1 < len(self.toks) and self.toks[pos].val == "[":
            pos += 2
        if pos >= len(self.toks) or self.toks[pos].kind != "IDENT":
            return False
        pos += 1
        if pos >= len(self.toks) or self.toks[pos].val != "(":
            return False
        depth = 0
        while pos < len(self.toks):
            v = self.toks[pos].val
            if v == "(":
                depth += 1
            elif v == ")":
                depth -= 1
                if depth == 0:
                    pos += 1
                    break
            pos += 1
        if pos < len(self.toks) and self.toks[pos].val == "throws":
            pos += 1
            while pos < len(self.toks) and self.toks[pos].val != "{":
                pos += 1
        return pos < len(self.toks) and self.toks[pos].val == "{"

    def _looks_like_var_decl(self) -> bool:
        t0 = self.cur(0)
        if t0.kind != "IDENT" or t0.val in _KEYWORDS:
            return False
        pos = self.idx + 1
        while (
            pos + 1 < len(self.toks)
            and self.toks[pos].val == "["
            and self.toks[pos + 1].val == "]"
        ):
            pos += 2
        if pos >= len(self.toks) or self.toks[pos].kind != "IDENT":
            return False
        after = self.toks[pos + 1].val if pos + 1 < len(self.toks) else ""
        return after in {"=", ";"}

    def _eat_type(self) -> str:
        t = self.eat("IDENT").val
        while self.match("OP", "[") and self.cur(1).val == "]":
            self.eat("OP", "[")
            self.eat("OP", "]")
        return t

    def parse_stmt_or_block(self) -> None:
        if self.match("OP", "{"):
            self.eat("OP", "{")
            start_len = len(self.em.lines)
            while not self.match("OP", "}") and not self.match("EOF"):
                self.parse_stmt()
            if len(self.em.lines) == start_len:
                self.em.emit("pass")
            self.eat("OP", "}")
        else:
            self.parse_stmt()

    def parse_stmt(self) -> None:
        if self.match("IDENT", "import"):
            while not self.match("OP", ";"):
                self.idx += 1
            self.eat("OP", ";")
            return
        if self.match("OP", "{"):
            self.eat("OP", "{")
            while not self.match("OP", "}"):
                self.parse_stmt()
            self.eat("OP", "}")
            return
        if self._looks_like_func_decl():
            self._eat_type()
            name = _py_ident(self.eat("IDENT").val)
            self.eat("OP", "(")
            params: list[str] = []
            while not self.match("OP", ")"):
                self._eat_type()
                params.append(_py_ident(self.eat("IDENT").val))
                if self.match("OP", ","):
                    self.eat("OP", ",")
            self.eat("OP", ")")
            if self.match("IDENT", "throws"):
                self.eat("IDENT", "throws")
                while not self.match("OP", "{"):
                    self.idx += 1
            self.em.emit(f"def {name}({', '.join(params)}):")
            self.em.indent += 1
            self.parse_stmt_or_block()
            self.em.indent -= 1
            return
        if self._looks_like_var_decl():
            self._eat_type()
            var_name = _py_ident(self.eat("IDENT").val)
            if self.match("OP", "="):
                self.eat("OP", "=")
                val = self.parse_expr()
                self.eat("OP", ";")
                self.em.emit(f"{var_name} = {val}")
            else:
                self.eat("OP", ";")
                self.em.emit(f"{var_name} = None")
            return
        if self.match("IDENT", "synchronized"):
            self.eat("IDENT", "synchronized")
            self.eat("OP", "(")
            self.parse_expr()
            self.eat("OP", ")")
            self.em.emit("with _env.lock:")
            self.em.indent += 1
            self.parse_stmt_or_block()
            self.em.indent -= 1
            return
        if self.match("IDENT", "try"):
            self.eat("IDENT", "try")
            self.em.emit("try:")
            self.em.indent += 1
            self.parse_stmt_or_block()
            self.em.indent -= 1
            while self.match("IDENT", "catch"):
                self.eat("IDENT", "catch")
                self.eat("OP", "(")
                self._eat_type()
                exc_name = _py_ident(self.eat("IDENT").val)
                self.eat("OP", ")")
                self.em.emit(f"except Exception as {exc_name}:")
                self.em.indent += 1
                self.parse_stmt_or_block()
                self.em.indent -= 1
            if self.match("IDENT", "finally"):
                self.eat("IDENT", "finally")
                self.em.emit("finally:")
                self.em.indent += 1
                self.parse_stmt_or_block()
                self.em.indent -= 1
            return
        if self.match("IDENT", "if"):
            self.eat("IDENT", "if")
            self.eat("OP", "(")
            cond = self.parse_expr()
            self.eat("OP", ")")
            self.em.emit(f"if {cond}:")
            self.em.indent += 1
            self.parse_stmt_or_block()
            self.em.indent -= 1
            while self.match("IDENT", "else"):
                self.eat("IDENT", "else")
                if self.match("IDENT", "if"):
                    self.eat("IDENT", "if")
                    self.eat("OP", "(")
                    econd = self.parse_expr()
                    self.eat("OP", ")")
                    self.em.emit(f"elif {econd}:")
                    self.em.indent += 1
                    self.parse_stmt_or_block()
                    self.em.indent -= 1
                else:
                    self.em.emit("else:")
                    self.em.indent += 1
                    self.parse_stmt_or_block()
                    self.em.indent -= 1
                    break
            return
        if self.match("IDENT", "while"):
            self.eat("IDENT", "while")
            self.eat("OP", "(")
            cond = self.parse_expr()
            self.eat("OP", ")")
            self.em.emit(f"while {cond}:")
            self.em.indent += 1
            self.parse_stmt_or_block()
            self.em.indent -= 1
            return
        if self.match("IDENT", "for"):
            self._parse_for_stmt()
            return
        if self.match("IDENT", "throw"):
            self.eat("IDENT", "throw")
            val = self.parse_expr()
            self.eat("OP", ";")
            self.em.emit(f"raise {val}")
            return
        if self.match("IDENT", "return"):
            self.eat("IDENT", "return")
            if self.match("OP", ";"):
                self.eat("OP", ";")
                self.em.emit("return None")
            else:
                val = self.parse_expr()
                self.eat("OP", ";")
                self.em.emit(f"return {val}")
            return
        if self.match("IDENT", "break"):
            self.eat("IDENT", "break")
            self.eat("OP", ";")
            self.em.emit("break")
            return
        if self.match("IDENT", "continue"):
            self.eat("IDENT", "continue")
            self.eat("OP", ";")
            self.em.emit("continue")
            return
        if self.match("OP", ";"):
            self.eat("OP", ";")
            return
        stmt = self._parse_simple_stmt()
        self.eat("OP", ";")
        self.em.emit(stmt)

    def _parse_for_stmt(self) -> None:
        self.eat("IDENT", "for")
        self.eat("OP", "(")
        init_line = None
        if not self.match("OP", ";"):
            if self._looks_like_var_decl():
                self._eat_type()
                vname = _py_ident(self.eat("IDENT").val)
                self.eat("OP", "=")
                init_line = f"{vname} = {self.parse_expr()}"
            else:
                init_line = self._parse_simple_stmt()
        self.eat("OP", ";")
        cond = self.parse_expr() if not self.match("OP", ";") else "True"
        self.eat("OP", ";")
        step_line = self._parse_simple_stmt() if not self.match("OP", ")") else None
        self.eat("OP", ")")

        self.em.loop_id += 1
        flag = f"_loop_ran_{self.em.loop_id}"
        if init_line:
            self.em.emit(init_line)
        self.em.emit(f"{flag} = False")
        self.em.emit("while True:")
        self.em.indent += 1
        if step_line:
            self.em.emit(f"if {flag}:")
            self.em.indent += 1
            self.em.emit(step_line)
            self.em.indent -= 1
        self.em.emit(f"{flag} = True")
        self.em.emit(f"if not ({cond}):")
        self.em.indent += 1
        self.em.emit("break")
        self.em.indent -= 1
        self.parse_stmt_or_block()
        self.em.indent -= 1

    def _parse_simple_stmt(self) -> str:
        lhs = self.parse_postfix()
        if self.match("OP", "="):
            self.eat("OP", "=")
            return f"{lhs} = {self.parse_expr()}"
        if self.match("OP", "+="):
            self.eat("OP", "+=")
            return f"{lhs} += {self.parse_expr()}"
        if self.match("OP", "-="):
            self.eat("OP", "-=")
            return f"{lhs} -= {self.parse_expr()}"
        if lhs.endswith("._postinc_"):
            target = lhs[: -len("._postinc_")]
            return f"{target} += 1"
        if any(
            self.match("OP", op) for op in ("&&", "||", "+", "-", "*", "/", "?", "&")
        ):
            # Fallback if called on expression statement
            raise SyntaxError(
                f"Unsupported simple statement after {lhs} at {self.cur()}"
            )
        return lhs

    def parse_expr(self) -> str:
        if (
            self.cur(0).kind == "IDENT"
            and self.cur(1).val == "="
            and self.cur(1).kind == "OP"
        ):
            name = _py_ident(self.eat("IDENT").val)
            self.eat("OP", "=")
            return f"({name} := {self.parse_expr()})"
        return self.parse_ternary()

    def parse_ternary(self) -> str:
        cond = self.parse_or()
        if self.match("OP", "?"):
            self.eat("OP", "?")
            t_val = self.parse_expr()
            self.eat("OP", ":")
            f_val = self.parse_ternary()
            return f"({t_val} if ({cond}) else {f_val})"
        return cond

    def parse_or(self) -> str:
        left = self.parse_and()
        while self.match("OP", "||"):
            self.eat("OP", "||")
            left = f"({left} or {self.parse_and()})"
        return left

    def parse_and(self) -> str:
        left = self.parse_bit_or()
        while self.match("OP", "&&"):
            self.eat("OP", "&&")
            left = f"({left} and {self.parse_bit_or()})"
        return left

    def parse_bit_or(self) -> str:
        left = self.parse_bit_xor()
        while self.match("OP", "|"):
            self.eat("OP", "|")
            left = f"({left} | {self.parse_bit_xor()})"
        return left

    def parse_bit_xor(self) -> str:
        left = self.parse_bit_and()
        while self.match("OP", "^"):
            self.eat("OP", "^")
            left = f"({left} ^ {self.parse_bit_and()})"
        return left

    def parse_bit_and(self) -> str:
        left = self.parse_eq()
        while self.match("OP", "&"):
            self.eat("OP", "&")
            left = f"({left} & {self.parse_eq()})"
        return left

    def parse_eq(self) -> str:
        left = self.parse_rel()
        while self.match("OP", "==") or self.match("OP", "!="):
            op = self.eat("OP").val
            right = self.parse_rel()
            if right == "None":
                py_op = "is" if op == "==" else "is not"
                left = f"({left} {py_op} None)"
            elif left == "None":
                py_op = "is" if op == "==" else "is not"
                left = f"(None {py_op} {right})"
            else:
                left = f"({left} {op} {right})"
        return left

    def parse_rel(self) -> str:
        left = self.parse_shift()
        while any(self.match("OP", op) for op in ("<", "<=", ">", ">=")):
            op = self.eat("OP").val
            left = f"({left} {op} {self.parse_shift()})"
        return left

    def parse_shift(self) -> str:
        left = self.parse_add()
        while self.match("OP", ">>") or self.match("OP", "<<"):
            op = self.eat("OP").val
            left = f"({left} {op} {self.parse_add()})"
        return left

    def parse_add(self) -> str:
        left = self.parse_mul()
        while self.match("OP", "+") or self.match("OP", "-"):
            op = self.eat("OP").val
            right = self.parse_mul()
            if op == "+":
                left = f"_jadd({left}, {right})"
            else:
                left = f"({left} - {right})"
        return left

    def parse_mul(self) -> str:
        left = self.parse_unary()
        while self.match("OP", "*") or self.match("OP", "/") or self.match("OP", "%"):
            op = self.eat("OP").val
            right = self.parse_unary()
            if op == "*":
                left = f"({left} * {right})"
            elif op == "/":
                left = f"_jdiv({left}, {right})"
            else:
                left = f"({left} % {right})"
        return left

    def parse_unary(self) -> str:
        if self.match("OP", "!"):
            self.eat("OP", "!")
            return f"(not ({self.parse_unary()}))"
        if self.match("OP", "-"):
            self.eat("OP", "-")
            return f"(-({self.parse_unary()}))"
        if (
            self.match("OP", "(")
            and self.cur(1).kind == "IDENT"
            and self.cur(1).val in _KNOWN_CAST_TYPES
            and self.cur(2).val == ")"
        ):
            self.eat("OP", "(")
            self.eat("IDENT")
            self.eat("OP", ")")
            return self.parse_unary()
        return self.parse_postfix()

    def parse_postfix(self) -> str:
        expr = self.parse_primary()
        while True:
            if self.match("OP", "."):
                self.eat("OP", ".")
                member = self.eat("IDENT").val
                if self.match("OP", "("):
                    args = self._parse_arg_list()
                    arg_s = ", ".join([expr, repr(member), *args])
                    expr = f"_jcall({arg_s})"
                else:
                    expr = f"_jattr({expr}, {member!r})"
            elif self.match("OP", "["):
                self.eat("OP", "[")
                idx = self.parse_expr()
                self.eat("OP", "]")
                expr = f"{expr}[{idx}]"
            elif self.match("OP", "++"):
                self.eat("OP", "++")
                expr = f"{expr}._postinc_"
            else:
                break
        return expr

    def _parse_arg_list(self) -> list[str]:
        self.eat("OP", "(")
        args: list[str] = []
        while not self.match("OP", ")"):
            args.append(self.parse_expr())
            if self.match("OP", ","):
                self.eat("OP", ",")
        self.eat("OP", ")")
        return args

    def parse_primary(self) -> str:
        t = self.cur()
        if t.kind == "NUM":
            self.idx += 1
            return repr(t.val)
        if t.kind == "STR":
            self.idx += 1
            return repr(t.val)
        if t.kind == "IDENT":
            if t.val == "true":
                self.idx += 1
                return "True"
            if t.val == "false":
                self.idx += 1
                return "False"
            if t.val == "null":
                self.idx += 1
                return "None"
            if t.val == "new":
                self.idx += 1
                type_name = self.eat("IDENT").val
                if self.match("OP", "["):
                    self.eat("OP", "[")
                    if not self.match("OP", "]"):
                        size_expr = self.parse_expr()
                        self.eat("OP", "]")
                        if type_name == "byte":
                            return f"bytearray({size_expr})"
                        return f"([0] * ({size_expr}))"
                    self.eat("OP", "]")
                    self.eat("OP", "{")
                    elems: list[str] = []
                    while not self.match("OP", "}"):
                        elems.append(self.parse_expr())
                        if self.match("OP", ","):
                            self.eat("OP", ",")
                    self.eat("OP", "}")
                    return f"[{', '.join(elems)}]"
                args = self._parse_arg_list()
                return f"{type_name}({', '.join(args)})"
            name = _py_ident(self.eat("IDENT").val)
            if self.match("OP", "("):
                args = self._parse_arg_list()
                return f"{name}({', '.join(args)})"
            return name
        if self.match("OP", "("):
            self.eat("OP", "(")
            inner = self.parse_expr()
            self.eat("OP", ")")
            return f"({inner})"
        raise SyntaxError(f"Unexpected token {t}")


def substitute_macro_vars(script_text: str, local_vars: dict[str, str]) -> str:
    """Replace MacroDroid ``{lv=name}`` placeholders using Java string escaping."""

    def repl(match: re.Match[str]) -> str:
        key = match.group(1)
        val = local_vars.get(key, "")
        return (
            val.replace("\\", "\\\\")
            .replace('"', '\\"')
            .replace("\n", "\\n")
            .replace("\r", "\\r")
        )

    return re.sub(r"\{lv=([A-Za-z0-9_]+)\}", repl, script_text)


def compile_bsh_to_python(script_text: str, local_vars: dict[str, str]) -> str:
    """Compile a Komobot BeanShell script to Python source code."""
    resolved = substitute_macro_vars(script_text, local_vars)
    tokens = _tokenize(resolved)
    return _BshToPyCompiler(tokens).compile_script()


@functools.lru_cache(maxsize=16)
def _compile_cached(script_text: str, frozen_vars: tuple[tuple[str, str], ...]):
    py_src = compile_bsh_to_python(script_text, dict(frozen_vars))
    return compile(py_src, "<bsh_script>", "exec")


def run_bsh_script(
    script_text: str, env: MockAndroidEnv, local_vars: dict[str, str] | None = None
) -> Any:
    """Compile and execute a BeanShell JavaAction script against ``MockAndroidEnv``."""
    frozen = tuple(sorted((local_vars or {}).items()))
    code = _compile_cached(script_text, frozen)
    ns = _make_runtime_globals(env)
    exec(code, ns, ns)
    return ns.get("__bsh_result__")
