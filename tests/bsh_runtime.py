class _MockBufferedReader:
    def __init__(self, reader: _MockInputStreamReader) -> None:
        self._reader = reader
        self._lines = reader.stream.read_all_lines()
        self._idx = 0

    def readLine(self) -> str | None:
        if self._idx >= len(self._lines):
            return None
        line = self._lines[self._idx]
        self._idx += 1
        return line

    def close(self) -> None:
        self._reader.close()


